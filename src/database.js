// ============================================
// HẢI APPLE STORE - POSTGRESQL DATABASE
// NODE.JS + PG + NEON
// ============================================

require("dotenv").config();

const { Pool } = require("pg");
const bcrypt = require("bcryptjs");

if (!process.env.DATABASE_URL) {
    throw new Error("Thiếu DATABASE_URL trong file .env hoặc Environment Variables!");
}

const pool = new Pool({
    connectionString: process.env.DATABASE_URL,
    ssl: {
        rejectUnauthorized: false
    },
    max: 10,
    idleTimeoutMillis: 30000,
    connectionTimeoutMillis: 15000
});

pool.on("error", (error) => {
    console.error("POSTGRESQL POOL ERROR:", error);
});

// ============================================
// KHỞI TẠO CƠ SỞ DỮ LIỆU
// ============================================

async function initDatabase() {
    const client = await pool.connect();

    try {
        await client.query("BEGIN");

        // USERS
        await client.query(`
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR(100) NOT NULL,
                email VARCHAR(255) NOT NULL UNIQUE,
                password TEXT NOT NULL,
                role VARCHAR(20) NOT NULL DEFAULT 'user',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        `);

        // PRODUCTS
        await client.query(`
            CREATE TABLE IF NOT EXISTS products (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR(255) NOT NULL,
                price NUMERIC(15,2) NOT NULL DEFAULT 0,
                image TEXT DEFAULT '',
                description TEXT DEFAULT '',
                category VARCHAR(100) DEFAULT 'iPhone',
                stock INTEGER NOT NULL DEFAULT 100,
                original_price NUMERIC(15,2) NOT NULL DEFAULT 0,
                featured INTEGER NOT NULL DEFAULT 0,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        `);

        // ORDERS
        await client.query(`
            CREATE TABLE IF NOT EXISTS orders (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
                fullname VARCHAR(150) NOT NULL,
                phone VARCHAR(20) NOT NULL,
                address TEXT NOT NULL,
                payment VARCHAR(20) NOT NULL,
                total NUMERIC(15,2) NOT NULL DEFAULT 0,
                status VARCHAR(50) NOT NULL DEFAULT 'Đang xử lý',
                payment_status VARCHAR(50) NOT NULL DEFAULT 'Chưa thanh toán',
                note TEXT DEFAULT '',
                transfer_reported_at TIMESTAMP,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        `);

        // ORDER ITEMS
        await client.query(`
            CREATE TABLE IF NOT EXISTS order_items (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
                product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
                product_name VARCHAR(255) NOT NULL,
                price NUMERIC(15,2) NOT NULL DEFAULT 0,
                quantity INTEGER NOT NULL DEFAULT 1,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        `);

        // REVIEWS
        await client.query(`
            CREATE TABLE IF NOT EXISTS reviews (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                order_id BIGINT REFERENCES orders(id) ON DELETE SET NULL,
                rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
                comment TEXT NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                UNIQUE(user_id, product_id)
            )
        `);

        // COUPONS
        await client.query(`
            CREATE TABLE IF NOT EXISTS coupons (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                code VARCHAR(100) NOT NULL UNIQUE,
                description TEXT DEFAULT '',
                discount_type VARCHAR(20) DEFAULT 'percent',
                discount_value NUMERIC(15,2) NOT NULL DEFAULT 0,
                min_order NUMERIC(15,2) NOT NULL DEFAULT 0,
                max_discount NUMERIC(15,2),
                usage_limit INTEGER,
                used_count INTEGER NOT NULL DEFAULT 0,
                start_date TIMESTAMP,
                end_date TIMESTAMP,
                active INTEGER NOT NULL DEFAULT 1,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        `);

        // COUPON USAGES
        await client.query(`
            CREATE TABLE IF NOT EXISTS coupon_usages (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                coupon_id BIGINT NOT NULL REFERENCES coupons(id) ON DELETE CASCADE,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                order_id BIGINT REFERENCES orders(id) ON DELETE SET NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        `);

        // FAVORITES
        await client.query(`
            CREATE TABLE IF NOT EXISTS favorites (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                UNIQUE(user_id, product_id)
            )
        `);

        // INDEXES
        await client.query(`
            CREATE INDEX IF NOT EXISTS idx_products_featured
            ON products(featured DESC, id DESC)
        `);

        await client.query(`
            CREATE INDEX IF NOT EXISTS idx_orders_user
            ON orders(user_id, id DESC)
        `);

        await client.query(`
            CREATE INDEX IF NOT EXISTS idx_order_items_order
            ON order_items(order_id)
        `);

        await client.query(`
            CREATE INDEX IF NOT EXISTS idx_reviews_product
            ON reviews(product_id, id DESC)
        `);

        await client.query(`
            CREATE INDEX IF NOT EXISTS idx_favorites_user
            ON favorites(user_id)
        `);

        // TẠO TÀI KHOẢN ADMIN NẾU CHƯA CÓ
        if (process.env.ADMIN_PASSWORD) {
            const adminEmail = "admin@iphoneshop.com";

            const existingAdmin = await client.query(
                "SELECT id FROM users WHERE email = $1",
                [adminEmail]
            );

            if (existingAdmin.rows.length === 0) {
                const hashedPassword = await bcrypt.hash(
                    process.env.ADMIN_PASSWORD,
                    10
                );

                await client.query(
                    `INSERT INTO users (name, email, password, role)
                     VALUES ($1, $2, $3, 'admin')`,
                    ["Quản trị viên", adminEmail, hashedPassword]
                );

                console.log("Đã tạo tài khoản quản trị viên!");
            }
        }

        await client.query("COMMIT");

        console.log("=================================");
        console.log("HẢI APPLE STORE");
        console.log("PostgreSQL đã khởi tạo thành công!");
        console.log("Các bảng dữ liệu đã sẵn sàng.");
        console.log("=================================");

    } catch (error) {
        await client.query("ROLLBACK");
        console.error("DATABASE INIT ERROR:", error);
        throw error;
    } finally {
        client.release();
    }
}

module.exports = {
    pool,
    initDatabase
};